#!/usr/bin/env python3
"""Embed the frozen default NNUE bytes; standard library only, no training."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ACTIVE=json.loads((ROOT/'models/default-model.json').read_text())
MODEL=ROOT/ACTIVE['defaultModel']
OUTPUT=ROOT/'cpp/model/default_nnue.inc'

def generate():
    data=MODEL.read_bytes()
    expected=json.loads(MODEL.with_suffix('.json').read_text())['sha256']
    digest=hashlib.sha256(data).hexdigest()
    if digest!=expected or digest!=ACTIVE['modelSha256']:raise ValueError('Default NNUE checksum does not match frozen metadata')
    lines=['// Generated by scripts/embed-default-model.py; do not edit.',
           f'// Source: {ACTIVE["defaultModel"]}; training attribution: data/README.md.',
           f'static constexpr char defaultModelSha256[]="{digest}";',
           'static constexpr unsigned char defaultModelBytes[]={']
    lines.extend('    '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24))
    lines.append('};')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=text:raise SystemExit('Embedded default model is stale; run scripts/embed-default-model.py')
        print('Embedded NNUE bytes and SHA-256 verified')
    else:OUTPUT.write_text(text);print('Embedded default NNUE:',MODEL.name)
